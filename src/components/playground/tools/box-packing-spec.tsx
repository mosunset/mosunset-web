/**
 * 箱詰めシミュレーターの仕様（第 4 版）。ツールのページの下に、開いて読める形で載せる。
 * ツール本体と違って文章だけなので、サーバーでも描画する（検索エンジンにも読ませる）
 */
export function BoxPackingSpec() {
  return (
    <details className="mt-10 rounded-lg border p-4">
      <summary className="cursor-pointer font-semibold">
        このツールの仕様
      </summary>
      <div className="prose prose-neutral dark:prose-invert mt-4 max-w-none prose-sm">
        <h2>1. 目的</h2>
        <p>
          決まった広さの床の上に、段ボール箱をなるべく低く、下から詰めて積みます。高さはいくらでも使えます。並べ方を計算して
          3D で見せ、結果を書き出せるようにします。
        </p>
        <ul>
          <li>
            計算も書き出しもブラウザの中だけで行い、入力した内容はどこにも送りません。
          </li>
        </ul>

        <h2>2. 入力</h2>
        <h3>2-1. 床と壁</h3>
        <ul>
          <li>
            <strong>単位：</strong>mm の整数で固定します。
          </li>
          <li>
            <strong>床：</strong>幅 X と奥行き Y。
          </li>
          <li>
            <strong>壁：</strong>
            奥・左・右をそれぞれオン・オフで選べます（0〜3
            面）。手前は荷物を出し入れする側なので、壁は置けません。
          </li>
        </ul>

        <h3>2-2. 箱のリスト</h3>
        <p>1 行に 1 種類で、ユーザーが次を入力します。</p>
        <table>
          <thead>
            <tr>
              <th>項目</th>
              <th>内容</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>X（幅）</td>
              <td>mm の整数</td>
            </tr>
            <tr>
              <td>Y（奥行き）</td>
              <td>mm の整数</td>
            </tr>
            <tr>
              <td>Z（高さ）</td>
              <td>mm の整数。そのまま置いたときに上を向く辺</td>
            </tr>
            <tr>
              <td>タグ</td>
              <td>
                自由に入力できる文字（例：「冬服」「食器・割れ物」）。空のときは「箱
                1」「箱 2」…と表示する
              </td>
            </tr>
            <tr>
              <td>個数</td>
              <td>同じ箱がいくつあるか</td>
            </tr>
            <tr>
              <td>横倒しの許可</td>
              <td>オン・オフ</td>
            </tr>
          </tbody>
        </table>
        <ul>
          <li>
            <strong>横倒しの許可：</strong>
            箱ごとに切り替えられます。全体でまとめてオン・オフもでき、一部だけオンのときは「混在」と表示します。オンは「横倒しにしてもよい」という許可です。倒すかどうかは計算で決め、倒したほうが良いときだけ倒します。
          </li>
          <li>
            <strong>色：</strong>同じタグの箱は同じ色で表示します。
          </li>
          <li>
            <strong>個数の目安：</strong>30 個前後で快適に動くこと。上限は全部で
            200 個くらいです。
          </li>
        </ul>

        <h3>2-3. ランダム箱の生成（テスト用）</h3>
        <p>
          ボタン 1
          つで、箱のリストをランダムに作ります。「詳しく」を開くと、作り方を変えられます。
        </p>
        <table>
          <thead>
            <tr>
              <th>項目</th>
              <th>初期値</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>箱の種類の数</td>
              <td>5 種類</td>
            </tr>
            <tr>
              <td>全部の個数</td>
              <td>30 個</td>
            </tr>
            <tr>
              <td>1 辺の長さの範囲</td>
              <td>150〜600 mm</td>
            </tr>
            <tr>
              <td>横倒しを許可する割合</td>
              <td>50%</td>
            </tr>
          </tbody>
        </table>
        <ul>
          <li>
            <strong>リストへの入れ方：</strong>
            今のリストを置き換えるか、後ろに足すかを選べます。置き換えるときは、消える前に確認します。
          </li>
          <li>
            <strong>タグ：</strong>「テスト A」「テスト
            B」…と自動で付けます。あとから書き換えられます。
          </li>
          <li>
            <strong>同じ箱の再現：</strong>
            生成のたびに番号（シード）を表示します。同じ番号を入れれば同じ箱を作れます。番号は
            JSON の書き出しにも入れます。
          </li>
          <li>
            <strong>はみ出し防止：</strong>1
            辺の長さは、床の幅・奥行きからすき間を引いた長さまでに抑えます。床からはみ出す箱は作りません。
          </li>
        </ul>

        <h3>2-4. 積み方の設定</h3>
        <table>
          <thead>
            <tr>
              <th>項目</th>
              <th>範囲</th>
              <th>初期値</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>箱どうしのすき間</td>
              <td>0〜50 mm</td>
              <td>5 mm</td>
            </tr>
            <tr>
              <td>箱と床の端・壁とのすき間</td>
              <td>0〜50 mm</td>
              <td>5 mm</td>
            </tr>
            <tr>
              <td>底面を支える割合</td>
              <td>50〜100%</td>
              <td>90%</td>
            </tr>
            <tr>
              <td>優先すること（トグル）</td>
              <td>「全体の高さを低く」/「下の段から隙間なく」</td>
              <td>全体の高さを低く</td>
            </tr>
            <tr>
              <td>重心の寄せ具合（壁があるとき）</td>
              <td>弱〜強</td>
              <td>中くらい</td>
            </tr>
          </tbody>
        </table>

        <h2>3. 守るルール（必ず守る）</h2>
        <ol>
          <li>
            <strong>はみ出さない：</strong>
            箱は、床の端から決めたすき間より内側に置きます。壁がある辺も同じです。
          </li>
          <li>
            <strong>めり込まない：</strong>
            箱どうしは重なりません。横に並ぶ箱の間は、決めたすき間をあけます。
          </li>
          <li>
            <strong>浮かせない：</strong>
            底面の決めた割合以上が、床か下の箱の上面に乗っていること。
          </li>
          <li>
            <strong>向きを変えるのは次の 2 つだけ（逆さまは扱わない）：</strong>
            床の上で 90°
            回す（すべての箱でできる）。横倒しにする（許可した箱だけ）。
          </li>
        </ol>

        <h2>4. 良い積み方の判断</h2>
        <h3>4-1. 優先すること（トグルで切り替え）</h3>
        <ul>
          <li>
            <strong>全体の高さを低く：</strong>
            いちばん大事なのは、全体が低いこと。次に、下のほうに箱が集まっていること。
          </li>
          <li>
            <strong>下の段から隙間なく：</strong>いちばん大事なのは、1
            段目の床が多く埋まっていること。次に、全体が低いこと。
          </li>
        </ul>
        <h3>4-2. 重心の位置（どちらのモードでも見る）</h3>
        <ul>
          <li>
            <strong>壁がないとき：</strong>全体の重心を、床の X・Y
            の中心に近づけます。
          </li>
          <li>
            <strong>壁があるとき：</strong>
            重心を、壁のある側に少しだけ寄せます。どのくらい寄せるかはスライダーで決めます。奥と左の壁なら、奥の左の角のほうに寄せます。左右両方に壁があるなら、左右は中央のままです。
          </li>
          <li>
            <strong>重さの扱い：</strong>
            どの箱も中身は均一で、重さは体積に比例するものとして計算します。
          </li>
        </ul>
        <h3>4-3. ぽつんと高い塔を避ける（禁止ではなく、評価を下げる）</h3>
        <ul>
          <li>
            壁から離れた側（手前や、壁のない側）に、まわりより飛び抜けて高い山ができる並べ方は評価を下げます。
          </li>
          <li>
            壁があるときは、壁側が高く、離れるほど低くなる形を良いとします。
          </li>
        </ul>

        <h2>5. 計算のしかた</h2>
        <ul>
          <li>
            ぴったりの最適解を出すのは難しい問題です。そこで、並べ順を何通りも試し、1
            個ずつ、その時点でいちばん良い場所に置いていきます。
          </li>
          <li>
            <strong>計算は裏で続けます（画面は固まらない）：</strong>
            今までで一番良い結果を、計算中もずっと表示します。もっと良い結果が見つかるたびに入れ替わります。良さそうな結果は候補として保存します。表示が入れ替わっても消えず、あとから選び直して見比べられます。
          </li>
          <li>
            <strong>計算を止める条件：</strong>
            「停止」ボタンを押したとき。一定時間（例えば 30
            秒）、良い結果が出なくなったとき。設定を変えたとき（新しい設定で、最初から計算し直す）。
          </li>
        </ul>

        <h2>6. 結果の表示</h2>
        <h3>6-1. 3D 表示</h3>
        <ul>
          <li>
            <strong>見え方：</strong>
            回転・拡大・移動ができます。床・壁・重心の位置を表示します。床は半透明にもでき、下の面も確かめられます。
          </li>
          <li>
            <strong>向きの文字：</strong>6
            つの面すべてに「上・下・左・右・前・後」を貼ります。基準は、入力したときの向きです（Z
            が上、Y
            が奥）。横倒しにした箱は、上を向いた面に「前」や「右」と出るので、どう倒したかが一目で分かります。
          </li>
          <li>
            <strong>タグ：</strong>
            いま上を向いている面と、手前を向いている面の中央に大きく出します。向きの文字は、面の隅に小さく出します。
          </li>
          <li>
            <strong>小さい箱：</strong>
            文字が収まらないときは縮めます。読めない大きさになるときは、文字を出さず色だけで見分けます。
          </li>
          <li>
            <strong>切り替え：</strong>
            「タグ」と「向きの文字」を、それぞれ別にオン・オフできます。
          </li>
          <li>
            <strong>ホバーとタップ：</strong>
            箱にカーソルを当てるか、スマホでタップすると、タグ・寸法・積んだ順番・上を向いている面を表示します。
          </li>
        </ul>
        <h3>6-2. 数字と一覧</h3>
        <ul>
          <li>
            <strong>数字：</strong>
            全体の高さ、充填率（箱の体積の合計 ÷ 床の面積 × 高さ）、1
            段目の埋まり具合、置けた個数 / 全部の個数、重心の位置。
          </li>
          <li>
            <strong>積む順に見る：</strong>スライダーで 1
            個ずつ、積んでいく様子を確かめられます。
          </li>
          <li>
            <strong>置けなかった箱：</strong>
            理由を付けて一覧にします（「床より大きい」「支えが足りない」）。
          </li>
          <li>
            <strong>置き場所の一覧：</strong>1 行に 1 箱で、順番・タグ・位置（x,
            y, z）・置いた向きの寸法・上を向いている面を出します。行を選ぶと、3D
            の中のその箱を目立たせます。
          </li>
          <li>
            <strong>候補の一覧：</strong>
            保存した候補を、高さ・充填率などと一緒に並べます。選んだ候補を、3D
            と一覧に表示します。
          </li>
        </ul>

        <h2>7. 書き出し・読み込み</h2>
        <ul>
          <li>
            <strong>CSV：</strong>
            選んでいる結果の、置き場所の一覧。Excel
            で開いても文字化けしないようにします。
          </li>
          <li>
            <strong>JSON：</strong>
            設定（ランダム生成の番号を含む）と、選んでいる結果をまとめたもの。
          </li>
          <li>
            <strong>PNG：</strong>今の 3D 表示の画像。
          </li>
          <li>
            <strong>JSON の読み込み：</strong>書き出した JSON
            を読み込むと、同じ設定に戻せます。
          </li>
        </ul>

        <h2>8. やらないこと</h2>
        <p>
          重さの違い、つぶれやすさ、取り出す順番、逆さまに置くことは扱いません。
        </p>
      </div>
    </details>
  )
}
