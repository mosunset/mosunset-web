import type { ReactNode } from 'react'

/** 見出しと行からなる表 */
function SpecTable({ head, rows }: { head: string[]; rows: ReactNode[][] }) {
  return (
    <table>
      <thead>
        <tr>
          {head.map((h) => (
            <th key={h}>{h}</th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.map((cells) => (
          <tr key={String(cells[0])}>
            {cells.map((c, i) => (
              // biome-ignore lint/suspicious/noArrayIndexKey: 列の位置が識別子
              <td key={i}>{c}</td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  )
}

